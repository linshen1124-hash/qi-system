-- 自有却无证，转为一条真正要办的权证事项
insert into cert_task (name, task_type, property_id, site, stage, start_date, owner, notes)
select '万寿路27号院8号楼8层 权属登记（自有未办证）','初始登记', 23,
  '海淀区万寿路27号院8号楼8层','未启动','2026-08-04','后勤管理处',
