-- 按资产台账《发后勤.xlsx》与《院房屋总体情况表.xls》校准房产台账（用户 2026-08-05 逐条裁定）
-- 方案甲：保留幢与证载面积不动，另加「所属资产卡片」建立 Excel 拆法的归属关系，
--         两套口径并存、可互相核对，不用一套盖掉另一套。

begin;

-- ========== 1. 结构 ==========
alter table property
  add column if not exists asset_card_id bigint references asset_card(id) on delete set null,
  add column if not exists cert_mark     text;

comment on column property.asset_card_id is '所属资产卡片（财务口径）。一张卡片可含多幢，如「其他用房（7号楼，锅炉房、车库，平房等）」';
comment on column property.cert_mark is '证载标记：证载计面积 / 证载不计面积（画叉，拆迁不计补偿）/ 未登记';

-- ========== 2. 幢 → 资产卡片归属 ==========
update property p set asset_card_id = a.id from asset_card a
 where (p.building, a.asset_no) in (
  -- 安定门：4号食堂经用户裁定归入「科研楼」（11368㎡）那张卡片
  ('1号科研楼','FW1990000001'), ('4号食堂','FW1990000001'),
  ('2号办公楼','FW1950000001'), ('3号办公楼','FW1950000002'),
  ('5号楼（活动室及餐厅）','FW1990000002'),
  -- 「其他用房（7号楼，锅炉房、车库，平房等）」是 Excel 自己写明的打包卡片
  ('7号配电室','FW1980000001'), ('锅炉房','FW1980000001'), ('车库','FW1980000001'),
  ('小平房','FW1980000001'), ('2、3号房（台账未记楼名）','FW1980000001'),
  ('家属门卫室','FW1980000001'), ('北侧门面房','FW1980000001'),
  -- 亦庄：整个院区一张卡片
  ('门卫','FW2008000001'), ('A座科研楼','FW2008000001'), ('B座大厅','FW2008000001'),
  ('C座电磁兼容','FW2008000001'), ('D座服务楼','FW2008000001'), ('E座科研楼','FW2008000001'),
  ('动力站','FW2008000001'), ('F座科研楼','FW2008000001'),
  -- 其余各处一卡一幢
  ('8号楼8层','FW2012000018'),
  ('经干院宿舍（地下室）','FW1996000001'),
  ('南湖中园101（109号楼）','FW2002000001'),
  ('南湖中园102（110号楼）','FW2002000002'),
  ('中雅大厦','FW2010000004'),
  ('门楼胡同3号','FW1990000005'),
  ('鼓楼大街1号','FW1990000006'));

-- ========== 3. 证载标记 ==========
update property set cert_mark = '证载计面积'
 where tenure='自有' and coalesce(cert_area,0) > 0;

-- 证上有影、面积为零：不是违法建筑，但拆迁不计补偿面积
update property set cert_mark = '证载不计面积（画叉，拆迁不计补偿）',
  notes = coalesce(notes,'') || ' 【2026-08-05】证上有登记但不计面积（画叉），属承认的合法建筑，'
    || '拆迁时不计入补偿面积。用户确认保留。'
 where id in (8, 12, 13);

update property set cert_mark = '未登记',
  notes = coalesce(notes,'') || ' 【2026-08-05】2015 年建成，不在任何权证内，也不在资产台账内，属未登记建筑。用户确认保留。'
 where id = 22;

update property set cert_mark = '证载计面积' where id = 34;

-- 2、3号房补充依据（源表已找到，写进备注免得下次再查一遍）
update property set notes = coalesce(notes,'') ||
  ' 依据：《电子标准院土地与建筑面积数据.xls》表一（2025-02-24）该行仅记房产证栋号「2、3」、'
  || '房产证建筑面积 0、实际建筑面积 116.1，前一行锅炉房（栋号4）备注「2、3号房产证无面积」。'
  || '注：本院区 13 幢的 cert_no 文本字段在迁移时被统一写成 030704，无区分力；'
  || 'cert_id 是按栋号连续性推定的——030704 证载 11 幢对应栋号 9~19（面积合计 14972.70 与证载分毫不差），'
  || '030705 证载 4 幢对应锅炉房+车库+小平房（498.30 与证载分毫不差），栋号 2、3 在两本证里都占不到面积位置。'
 where id = 8;

-- ========== 4. 删除老干部活动室（用户：没听说过这处房，取消）==========
-- 已确认无 cert_task / asset_card / lease 引用
delete from property where id = 11;

-- ========== 5. 中雅大厦按产证面积计入 ==========
-- 《院房屋总体情况表.xls》权属面积 247.51（单身宿舍），发后勤资产账面 257，差 9.49 属账实差
update property_cert set building_area = 247.51,
  notes = coalesce(notes,'') || ' 【2026-08-05】证载建筑面积按《院房屋总体情况表》权属面积记 247.51㎡；'
    || '资产台账《发后勤》账面面积为 257㎡，两者差 9.49㎡ 属账实差，账面数保留在资产卡片 FW2010000004。'
 where cert_no = 'X京房权证海字第197304号';
update property set cert_area = 247.51, actual_area = null,
  notes = coalesce(notes,'') || ' 【2026-08-05】证载面积按产证记 247.51㎡（原 257 为资产账面数，已移交资产卡片承载）。实测面积暂缺。'
 where id = 26;

-- ========== 6. 南湖中园：两套均在 110号楼5门 ==========
update property set building = '南湖中园110号楼5门101',
  address = '朝阳区南湖中园110号楼5门101',
  notes = coalesce(notes,'') || ' 【2026-08-05】地址按《院房屋总体情况表》更正：两套均在 110号楼5门，'
    || '门牌为 101、102。发后勤台账记 109号楼/110号楼 有误。'
 where id = 25;
update property set building = '南湖中园110号楼5门102',
  address = '朝阳区南湖中园110号楼5门102',
  notes = coalesce(notes,'') || ' 【2026-08-05】地址按《院房屋总体情况表》更正：与 101 同在 110号楼5门。'
 where id = 31;
update property_cert set address = '朝阳区南湖中园110号楼5门101'
 where cert_no = '朝全03字第01250号';
update property_cert set address = '朝阳区南湖中园110号楼5门102'
 where cert_no = '朝全03字第01251号';

-- ========== 7. 经干院宿舍地址更正 ==========
update property set address = '朝阳区望京中环南路5号院2号楼9门、10门',
  notes = coalesce(notes,'') || ' 【2026-08-05】地址按《院房屋总体情况表》更正为望京中环南路5号院2号楼9门、10门；'
    || '发后勤台账记「朝阳区爽秋路8号经济干部学院宿舍楼」有误。'
 where id = 24;

-- ========== 8. 鼓楼：改为鼓楼东大街24号 ==========
-- 这样与 28 户公有住房所在的「鼓楼东大街24号院」接上
update property set building = '鼓楼东大街24号',
  campus = '鼓楼东大街24号院',
  address = '东城区鼓楼东大街24号',
  notes = coalesce(notes,'') || ' 【2026-08-05】地址按《院房屋总体情况表》更正为鼓楼东大街24号；'
    || '发后勤台账记「鼓楼大街1号」有误。系统内 28 户公有住房所在的「鼓楼东大街24号院」即此处，'
    || '此前房产本体与住户分列两处名称，现已统一。'
 where id = 33;

-- ========== 9. 亦庄不动产权证号确认为 7 位 ==========
-- 《院房屋总体情况表.xls》独立记为「京（2017）开不动产权第0023850」，与证件原件一致，
-- 发后勤台账的 00238850（8位）为多打一个 8。同一格里的 2021 年证 0004549 是 7 位，可佐证。
update property_cert set notes = replace(notes,
  ' ⚠️ 院资产台账《发后勤》记为「京（2017）开不动产权00238850号」（8位），本条按证件原件记为 0023850（7位），需比对原件确认。',
  ' 【2026-08-05 已定】证号为 7 位 0023850：证件原件与《院房屋总体情况表》两个独立来源一致；'
  || '发后勤台账记 00238850（8位）为多打一个 8——同格内 2021 年证记 0004549 亦为 7 位，可佐证。')
 where cert_no = '京(2017)开不动产权第0023850号';

update cert_task set stage = '已终止', last_date = '2026-08-05',
  notes = coalesce(notes,'') || ' 【2026-08-05 结论】确认为 7 位 0023850。'
    || '《院房屋总体情况表.xls》独立记载与证件原件一致，发后勤台账多打一个 8。无需调原件。'
 where name = '亦庄不动产权证号位数待核';

insert into audit_log (actor, action, entity, entity_id, summary) values
 ('qi-agent@gmail.com','update','property',null,'按用户裁定校准房产台账：新增 asset_card_id 建立幢→资产卡片归属（方案甲，26 幢已归属，4号食堂归入FW1990000001）；新增 cert_mark 标记证载计/不计面积；删除老干部活动室；中雅大厦证载面积 257→247.51；南湖中园两套改为110号楼5门101/102；经干院改为望京中环南路5号院2号楼9门10门；鼓楼大街1号改为鼓楼东大街24号；亦庄证号确认7位');

commit;
