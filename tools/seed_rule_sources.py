def main():
    force = "--force" in sys.argv
    db.init_db()
    conn = db.get_conn()
    existing = conn.execute("SELECT COUNT(*) c FROM rule_source").fetchone()[0]
    if existing and not force:
        print(f"rule_source 已有 {existing} 条，跳过（如需重灌用 --force）")
        return
    if force:
        conn.execute("DELETE FROM rule_source")
    for name, doc_no, issuer, level, domain, year, url, sf in SOURCES:
        conn.execute(
            "INSERT INTO rule_source(name,doc_no,issuer,level,domain,year,url,source_file) "
            "VALUES(?,?,?,?,?,?,?,?)", (name, doc_no, issuer, level, domain, year, url, sf))
    conn.commit()
    print(f"✓ 已登记 {len(SOURCES)} 条制度依据 -> rule_source")
    by_level = {}
    for r in db.rows("SELECT level, COUNT(*) c FROM rule_source GROUP BY level ORDER BY c DESC"):
        by_level[r["level"]] = r["c"]
    for lv, c in by_level.items():
        print(f"  {lv:8s} {c}")


if __name__ == "__main__":
    main()
